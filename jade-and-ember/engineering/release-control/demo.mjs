// node engineering/release-control/demo.mjs : a narrated run of the release-control proof of concept through its real command line (G6-3A, APR-JE-043).
// SYNTHETIC: a throwaway client site is built and prepared by the real release tool in the dry run's throwaway copy; release control runs on a throwaway folder with
// disposable tokens; "deployment" is a copy into that folder. Nothing touches GitHub, a host, a credential or any real record.
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { dirname, join, resolve } from 'node:path';
import { createSandbox } from '../lib/release-dryrun.mjs';
import { DEFAULT_DATA_FILES, buildView } from './lib/view.mjs';
import { tempDir } from '../lib/git.mjs';

const cli = resolve(import.meta.dirname, 'cli.mjs');
const say = (s = '') => console.log(s);
const sb = createSandbox({ flavour: 'client' });
const snap = buildView(join(sb.proj, 'engineering'), new Map());
const pack = (label) => {
  const r = sb.tool(['prepare']); if (r.status !== 0) throw new Error(`prepare failed: ${r.out.slice(-200)}`);
  const d = tempDir(`demo-${label}`); cpSync(join(sb.proj, 'release'), d, { recursive: true }); mkdirSync(join(d, 'data'));
  for (const f of DEFAULT_DATA_FILES) if (existsSync(join(sb.proj, 'engineering', f))) cpSync(join(sb.proj, 'engineering', f), join(d, 'data', f));
  return d;
};
const first = pack('first');
sb.committed(() => sb.json('config/copy.json', (o) => { o.home.process.steps[0].text += ' We now start an hour earlier.'; }), 'synthetic: one sentence');
const textEdit = pack('text');
sb.restore();
sb.committed(() => sb.json('config/client.json', (o) => { o.ordering.url = 'https://order.jade-and-ember-fixture.com/menu-new'; }), 'synthetic: a changed link');
const linkEdit = pack('link');

const root = tempDir('demo-rc');
const as = (who, args) => { const r = spawnSync(process.execPath, [cli, ...args, '--rc', join(root, 'rc'), '--credential', join(root, 'operator', `${who}.token`)], { encoding: 'utf8' }); const out = (r.stdout + r.stderr).trimEnd(); say(`$ rc ${args.join(' ').replace(/--package \S+/, '--package <prepared package>')}   [as ${who}]`); say(out.split('\n').map((l) => `  ${l}`).join('\n')); say(); return { ...r, out }; };
const stageId = (r) => /STAGED (st-\S+):/.exec(r.out)?.[1];

say('# Release control: a local proof of concept (synthetic clients, disposable tokens, a throwaway folder)\n');
const init = spawnSync(process.execPath, [cli, 'init-demo', '--rc', root, '--clients', 'alpha,beta', '--hosts', 'alpha=www.jade-and-ember-fixture.com', '--tooling', snap.eng], { encoding: 'utf8' });
say(`$ rc init-demo --clients alpha,beta\n${init.stdout.trimEnd().split('\n').map((l) => `  ${l}`).join('\n')}\n`);

say('## 1. A coding agent tries to use release control: it has no capability at all\n');
as('agent', ['stage', '--client', 'alpha', '--package', first]);
as('agent', ['approve', '--client', 'alpha', '--stage', 'st-anything']);

say('## 2. The first release of a client is always the owner\'s decision (material)\n');
const s1 = stageId(as('scheduler', ['stage', '--client', 'alpha', '--package', first]));
say('The owner opens the review page (generated by release control; everything from the package is escaped data):');
const page = readFileSync(join(root, 'rc', 'staged', 'alpha', s1, 'review.html'), 'utf8').replace(/<style>[\s\S]*?<\/style>/, '').replace(/<[^>]+>/g, ' ').replace(/[ \t]+/g, ' ').replace(/\n\s*\n+/g, '\n');
say(page.split('\n').filter((l) => l.trim()).slice(0, 14).map((l) => `  | ${l.trim()}`).join('\n') + '\n');
as('owner', ['approve', '--client', 'alpha', '--stage', s1]);
for (const t of ['search', 'rights', 'externalLinks', 'domain']) as('owner', ['record-approval', '--client', 'alpha', '--stage', s1, '--type', t, '--note', 'looked at it (synthetic demo)', '--basis', 'licence']);
as('owner', ['approve', '--client', 'alpha', '--stage', s1]);

say('## 3. Routine maintenance: automatic only when the owner preauthorised that kind\n');
as('scheduler', ['run-scheduled', '--client', 'alpha', '--package', textEdit]);
as('owner', ['preauth-grant', '--client', 'alpha', '--kinds', 'identical,text-only', '--days', '30', '--max', '10']);
as('scheduler', ['run-scheduled', '--client', 'alpha', '--package', textEdit]);

say('## 4. A material change (a link changed) never goes out by itself\n');
const r4 = as('scheduler', ['run-scheduled', '--client', 'alpha', '--package', linkEdit]);
const s4 = /stage (st-\S+) is/.exec(r4.out)?.[1];
as('scheduler', ['auto-release', '--client', 'alpha', '--stage', s4]);
as('owner', ['approve', '--client', 'alpha', '--stage', s4]);
say('The same thing in one command: approve with a note saying what was checked (it records the open subjects for this stage, then releases).\n');
as('owner', ['approve', '--client', 'alpha', '--stage', s4, '--note', 'looked at the new link (synthetic demo)', '--basis', 'licence']);

say('## 5. Controls: revoke, freeze, audit\n');
as('owner', ['freeze', '--client', 'alpha', '--reason', 'demo: pausing releases']);
as('scheduler', ['stage', '--client', 'alpha', '--package', textEdit]);
as('owner', ['unfreeze', '--client', 'alpha', '--reason', 'demo: resuming']);
as('owner', ['audit', '--client', 'alpha']);
as('owner', ['status', '--client', 'beta']);
sb.destroy();
void dirname; void readdirSync;
